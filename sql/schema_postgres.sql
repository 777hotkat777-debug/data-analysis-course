CREATE TABLE protected_area_names (
    id_uc_g0 BIGINT NOT NULL,
    kind TEXT NOT NULL,
    ord INTEGER NOT NULL,
    name TEXT,
    PRIMARY KEY (id_uc_g0, kind, ord),
    FOREIGN KEY (id_uc_g0) REFERENCES urban_centres (id_uc_g0),
    CHECK (kind IN ('TPA','MPA'))
